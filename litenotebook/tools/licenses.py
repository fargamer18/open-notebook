def _license(dist: md.Distribution) -> str:
    meta = dist.metadata
    expr = meta.get("License-Expression")
    if expr:
        return expr
    classifiers = [
        c.split("::")[-1].strip()
        for c in meta.get_all("Classifier") or []
        if c.startswith("License ::") and "OSI Approved" != c.split("::")[-1].strip()
    ]
    text = (meta.get("License") or "").strip()
    if classifiers:
        return "; ".join(dict.fromkeys(classifiers))
    if text and len(text) < 120:
        return text
    return text.splitlines()[0][:100] + " (see package)" if text else "UNKNOWN"


def closure(roots: list[str]) -> dict[str, md.Distribution]:
    seen: dict[str, md.Distribution] = {}
    todo = list(roots)
    while todo:
        name = todo.pop()
        key = name.lower().replace("_", "-")
        if key in seen:
            continue
        try:
            dist = md.distribution(name)
        except md.PackageNotFoundError:
            continue
        seen[key] = dist
        for req in dist.requires or []:
            if "extra ==" in req:
                continue
            if (
                ";" in req
                and "sys_platform" in req
                and "win32" in req
                and sys.platform != "win32"
            ):
                continue
            m = _NAME.match(req.strip())
            if m:
                todo.append(m.group(1))
    return seen


def write_inventory(out: Path) -> list[tuple[str, str, str, str]]:
    core = closure(CORE_ROOTS)
    worker = closure(WORKER_ROOTS)
    rows = []
    for key in sorted(set(core) | set(worker)):
        dist = core.get(key) or worker[key]
        where = " + ".join(
            w for w, s in (("core", core), ("embedding runtime", worker)) if key in s
        )
        rows.append((dist.metadata["Name"], dist.version, where, _license(dist)))
    lines = [
        "# LiteNotebook — third-party components and licenses",
        "",
        "Generated by `tools/licenses.py` from installed package metadata. This is an",
        "inventory for review, **not legal advice**. LiteNotebook bundles only the",
        "components marked *bundled*; models, llama.cpp and speech are optional",
        "downloads the user chooses.",
        "",
        "> **PyMuPDF / MuPDF is AGPL-3.0-or-later (or a commercial license from",
        "> Artifex).** Distributing an application that includes it requires either",
        "> AGPL compliance for the distributed application (complete corresponding",
        "> source under AGPL-compatible terms, including for network use) or a",
        "> commercial PyMuPDF license. Review before any public distribution.",
        "",
        "## Python packages",
        "",
        "| Package | Version | In | License (from metadata) |",
        "|---|---|---|---|",
    ]
    lines += [f"| {n} | {v} | {w} | {lic} |" for n, v, w, lic in rows]
    lines += [
        "",
        "## Native and other bundled components",
        "",
        "| Component | Status | License |",
        "|---|---|---|",
    ]
    lines += [f"| {n} | {s} | {lic} |" for n, s, lic in NON_PYTHON]
    lines += [
        "",
        "## Optional components (never bundled)",
        "",
        "| Component | Status | License |",
        "|---|---|---|",
    ]
    lines += [f"| {n} | {s} | {lic} |" for n, s, lic in NOT_BUNDLED]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return rows


if __name__ == "__main__":
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("THIRD_PARTY_LICENSES.md")
    print(f"{len(write_inventory(target))} packages → {target}")
